#!/usr/bin/env python3
"""Turn recipes/mealplan-src.json into the recipe list inside mockup/fuel.dc.html.

Each ingredient line names a food in foods-db.json and a weight, so a recipe's calories and macros
come from the same official tables as the rest of the app. Photos and credits come from
photos/credits.json. The generated block sits between // RECIPES:BEGIN and // RECIPES:END.

  python3 tools/mkrecipes.py
"""
import json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
db = json.load(open(os.path.join(ROOT, 'foods-db.json')))
by_name = {}
for f in db['foods']:
    by_name.setdefault(f[0], f)
src = json.load(open(os.path.join(ROOT, 'recipes', 'mealplan-src.json')))
credits = json.load(open(os.path.join(ROOT, 'photos', 'credits.json')))
r1 = lambda v: round(v, 1)
out = []
for r in src:
    lines = []
    for l in r['lines']:
        f = by_name.get(l['food']) if l['food'] else None
        if l['food'] and not f:
            sys.exit(f"{r['id']}: food not in database: {l['food']}")
        k = (lambda i: (f[i] or 0) * l['g'] / 100) if f else (lambda i: 0)
        lines.append([l['t'], r1(k(4)), r1(k(5)), r1(k(6)), r1(k(7))])
    kc = sum(l[1] for l in lines); p = sum(l[2] for l in lines); c = sum(l[3] for l in lines); fat = sum(l[4] for l in lines)
    tags = []
    if p * 4 / max(kc, 1) >= 0.30: tags.append('hp')
    if c <= 20: tags.append('lowcarb')
    if r['mins'] <= 15: tags.append('quick')
    cats = list(r['slots'])
    cats += [t for t in tags]
    cats += r['diets']
    if kc < 500: cats.append('u500')
    o = {'id': r['id'], 'title': r['title'], 'time': r['time'], 'mins': r['mins'], 'slots': r['slots'], 'goals': r['goals'], 'diets': r['diets'], 'cats': cats, 'lines': lines, 'steps': r['steps']}
    c2 = credits.get(r['id'])
    if c2:
        o['photo'] = 'photos/' + r['id'] + '.jpg'
        o['credit'] = 'Photo: ' + c2['by'] + ' · ' + c2['license'] + ' · Wikimedia Commons'
        o['creditUrl'] = c2['page']
    out.append(o)
p = os.path.join(ROOT, 'mockup', 'fuel.dc.html')
s = open(p, encoding='utf-8').read()
block = '// RECIPES:BEGIN (generated by tools/mkrecipes.py from recipes/mealplan-src.json; do not edit by hand)\n    this.planRecipes = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n    // RECIPES:END'
if '// RECIPES:BEGIN' not in s:
    sys.exit('markers not found in mockup/fuel.dc.html')
s = re.sub(r'// RECIPES:BEGIN.*?// RECIPES:END', lambda m: block, s, flags=re.S)
open(p, 'w', encoding='utf-8').write(s)
print(len(out), 'recipes,', sum(1 for o in out if 'photo' in o), 'with photos,', len(block) // 1024, 'KB')
