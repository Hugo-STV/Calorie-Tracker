const { chromium } = require('playwright');
const fails = []; const expect = (ok, what) => { if (!ok) { fails.push(what); console.log('FAIL:', what); } };
(async () => {
  require('fs').mkdirSync(process.env.SHOTS || 'test-shots', { recursive: true });
  const b = await chromium.launch(); const page = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  await page.route('https://fonts.googleapis.com/**', (r) => r.abort());
  const errs = []; page.on('pageerror', (e) => errs.push(e.message));
  await page.goto('http://localhost:8765/');
  await page.evaluate(() => { localStorage.clear(); });
  await page.reload(); await page.waitForSelector('#nm');
  await page.evaluate(() => DC.comp.setState({ mode: 'app', view: 'log' }));
  await page.fill('input[aria-label="Search food"]', 'ham');
  await page.waitForSelector('text=Ham pie', { timeout: 8000 }); await page.getByText('Ham pie').first().click();
  await page.waitForSelector('#selg');
  const nums = async () => page.evaluate(() => { const v = DC.comp.renderVals(); return [v.sel.kcal, v.sel.p, v.servings, v.wg.hint]; });
  console.log('before:', JSON.stringify(await nums()));
  await page.fill('#selg', '62'); await page.waitForTimeout(200);
  console.log('62 g:', JSON.stringify(await nums()));
  await page.screenshot({ path: (process.env.SHOTS || 'test-shots') + '/20-weigh.png' });
  await page.getByRole('button', { name: 'oz', exact: true }).click(); await page.fill('#selg', '2'); await page.waitForTimeout(200);
  console.log('2 oz:', JSON.stringify(await nums()));
  await page.getByRole('button', { name: 'More servings' }).click(); await page.waitForTimeout(200);
  console.log('after +:', JSON.stringify(await nums()));
  await page.getByRole('button', { name: 'g', exact: true }).click(); await page.fill('#selg', '62'); await page.waitForTimeout(200);
  await page.getByRole('button', { name: /^Add to/ }).click(); await page.waitForTimeout(200);
  console.log('logged:', JSON.stringify(await page.evaluate(() => Object.values(DC.comp.state.log).flat().map((e) => [e.food.name, e.food.serving, e.food.kcal, e.servings]))));
  const logged = await page.evaluate(() => Object.values(DC.comp.state.log).flat().map((e) => [e.food.serving, e.food.kcal]));
  expect(logged.length === 1 && logged[0][0] === '62 g (weighed)' && logged[0][1] === 73, '62 g of ham pie logs 73 kcal');
  expect(!errs.length, 'no page errors');
  console.log('errors:', JSON.stringify(errs)); await b.close();
  if (fails.length) process.exit(1); console.log('all checks passed');
})().catch((e) => { console.error('TEST FAILED', String(e).slice(0, 300)); process.exit(1); });
